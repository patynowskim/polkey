#!/usr/bin/env python3
"""Generate rtl_pq/pq_kzetas.vh: ML-KEM zetas in Montgomery form (R = 2^32), zrom[256 + i]."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import kem_model as M
o = ["// generated by ref/kem/gen_kzetas.py: ML-KEM NTT zetas * 2^32 mod q (signed), zrom[256 + i]"]
for i, z in enumerate(M.ZM): o.append(f"zrom[{256 + i}] = {'-' if z < 0 else ''}32'sd{abs(z)};")
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "rtl_pq", "pq_kzetas.vh"), "w").write("\n".join(o) + "\n")
