#!/usr/bin/env python3
"""Generate fidokey/src/u2f_att_default.h: the shared default U2F attestation key + self-signed certificate.

The private key is public on purpose (it ships in every unit's firmware): all PolKeys then present the same
attestation identity, so a relying party cannot tell units apart. Provision a real batch key and certificate with
PROVISION_ATTESTATION for attested deployments.
"""
import datetime
import sys

from cryptography import x509
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.x509.oid import NameOID

# fixed key derived from a label, so the header is reproducible
import hashlib
d = int.from_bytes(hashlib.sha256(b"PolKey default attestation key v1").digest(), "big") % (2**256 - 2**224) + 1
key = ec.derive_private_key(d, ec.SECP256R1())
name = x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, "PolKey default attestation (shared)")])
cert = (x509.CertificateBuilder().subject_name(name).issuer_name(name).public_key(key.public_key())
        .serial_number(1).not_valid_before(datetime.datetime(2026, 1, 1)).not_valid_after(datetime.datetime(2049, 12, 31, 23, 59, 59))
        .sign(key, hashes.SHA256()))
der = cert.public_bytes(serialization.Encoding.DER)
raw = key.private_numbers().private_value.to_bytes(32, "big")


def arr(name, b):
    lines = ["    " + ", ".join(f"0x{x:02X}" for x in b[i:i + 12]) + "," for i in range(0, len(b), 12)]
    return f"static const uint8_t {name}[{len(b)}] = {{\n" + "\n".join(lines) + "\n};\n"


out = ("/* Generated by hw/bl616/tools/gen_att_default.py - shared default U2F attestation identity.\n"
       " * The private key is intentionally public: every unit uses the same one (no tracking by attestation). */\n"
       "#ifndef U2F_ATT_DEFAULT_H\n#define U2F_ATT_DEFAULT_H\n#include <stdint.h>\n\n"
       + arr("u2f_att_default_key", raw) + "\n" + arr("u2f_att_default_cert", der) + "\n#endif\n")
open(sys.argv[1] if len(sys.argv) > 1 else "u2f_att_default.h", "w").write(out)
print(f"certificate {len(der)} bytes")
